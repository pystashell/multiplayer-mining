export function translateServerMessage(locale: Locale, code: string | undefined, message: string): string {
  if (locale === "zh-CN") return message === "Not found" ? "没有找到这个房间。" : message;
  const direct = (EN as Record<string, string>)[message];
  if (direct) return direct;
  const rateLimited = /^发得太快了，请\s*(\d+)\s*秒后再试。$/.exec(message);
  if (rateLimited) return `You're sending messages too quickly. Try again in ${rateLimited[1]} seconds.`;
  if (!/[\u3400-\u9fff]/.test(message)) return message;
  return (code && ERROR_CODE_EN[code]) || "Something went wrong. Please try again.";
}

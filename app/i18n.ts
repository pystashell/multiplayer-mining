export type Locale = "zh-CN" | "en";

export function parseLocale(value: string | null | undefined): Locale | null {
  if (!value) return null;
  const normalized = value.trim().toLowerCase();
  if (normalized === "zh-cn" || normalized === "zh") return "zh-CN";
  if (normalized === "en" || normalized === "en-us" || normalized === "en-gb") return "en";
  return null;
}

export function localeFromLanguage(value: string | null | undefined): Locale {
  const primary = value?.split(",", 1)[0]?.split(";", 1)[0]?.trim().toLowerCase() ?? "";
  return primary === "zh" || primary.startsWith("zh-") ? "zh-CN" : "en";
}

